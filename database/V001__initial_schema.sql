-- Oracle Database 21c. Run in a new application schema inside XEPDB1.
CREATE TABLE schema_version (version NUMBER(10,0) PRIMARY KEY, applied_at TIMESTAMP(6) WITH TIME ZONE NOT NULL);
CREATE TABLE app_user (
  id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100 CHAR) NOT NULL,
  normalized_email VARCHAR2(254 CHAR) NOT NULL,
  password_hash VARCHAR2(255 CHAR) NOT NULL,
  role VARCHAR2(10 CHAR) NOT NULL,
  active NUMBER(1,0) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  version NUMBER(19,0) DEFAULT 0 NOT NULL,
  CONSTRAINT uq_user_email UNIQUE(normalized_email),
  CONSTRAINT ck_user_role CHECK(role IN ('USER','ADMIN')),
  CONSTRAINT ck_user_active CHECK(active IN (0,1))
);
CREATE TABLE stored_file (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  owner_id NUMBER(19,0) NOT NULL,
  original_name VARCHAR2(160 CHAR) NOT NULL,
  storage_key VARCHAR2(36 CHAR) NOT NULL,
  detected_mime_type VARCHAR2(100 CHAR) NOT NULL,
  size_bytes NUMBER(19,0) NOT NULL,
  description VARCHAR2(1000 CHAR),
  wrapped_data_key RAW(48) NOT NULL,
  wrapping_iv RAW(12) NOT NULL,
  file_iv RAW(12) NOT NULL,
  crypto_version NUMBER(10,0) NOT NULL,
  status VARCHAR2(20 CHAR) NOT NULL,
  created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  version NUMBER(19,0) DEFAULT 0 NOT NULL,
  CONSTRAINT fk_file_owner FOREIGN KEY(owner_id) REFERENCES app_user(id),
  CONSTRAINT uq_storage_key UNIQUE(storage_key),
  CONSTRAINT ck_file_size CHECK(size_bytes BETWEEN 1 AND 10485760),
  CONSTRAINT ck_file_status CHECK(status IN ('ACTIVE','DELETED'))
);
CREATE INDEX ix_file_owner_status ON stored_file(owner_id,status,created_at);
CREATE TABLE file_permission (
  id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_id VARCHAR2(36 CHAR) NOT NULL,
  recipient_id NUMBER(19,0) NOT NULL,
  permission VARCHAR2(10 CHAR) NOT NULL,
  granted_by NUMBER(19,0) NOT NULL,
  granted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  expires_at TIMESTAMP(6) WITH TIME ZONE,
  revoked_at TIMESTAMP(6) WITH TIME ZONE,
  version NUMBER(19,0) DEFAULT 0 NOT NULL,
  CONSTRAINT fk_permission_file FOREIGN KEY(file_id) REFERENCES stored_file(id),
  CONSTRAINT fk_permission_recipient FOREIGN KEY(recipient_id) REFERENCES app_user(id),
  CONSTRAINT fk_permission_grantor FOREIGN KEY(granted_by) REFERENCES app_user(id),
  CONSTRAINT uq_file_recipient UNIQUE(file_id,recipient_id),
  CONSTRAINT ck_download_permission CHECK(permission='DOWNLOAD')
);
CREATE INDEX ix_permission_recipient ON file_permission(recipient_id,revoked_at,expires_at);
CREATE TABLE audit_log (
  id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id NUMBER(19,0),
  file_id VARCHAR2(36 CHAR),
  action VARCHAR2(40 CHAR) NOT NULL,
  outcome VARCHAR2(10 CHAR) NOT NULL,
  reason_code VARCHAR2(60 CHAR) NOT NULL,
  occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_audit_actor FOREIGN KEY(actor_id) REFERENCES app_user(id),
  CONSTRAINT fk_audit_file FOREIGN KEY(file_id) REFERENCES stored_file(id)
);
CREATE INDEX ix_audit_time ON audit_log(occurred_at);
CREATE INDEX ix_audit_actor ON audit_log(actor_id,occurred_at);
CREATE INDEX ix_audit_action_outcome ON audit_log(action,outcome,occurred_at);
INSERT INTO schema_version VALUES(1,SYSTIMESTAMP);
